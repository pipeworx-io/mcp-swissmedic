const UA = 'pipeworx-mcp-swissmedic/1.0 (+https://pipeworx.io)';
const SOURCE = 'Swissmedic — Zugelassene Arzneimittel HAM (authorised human medicines, Switzerland)';

// Swissmedic states a MONTHLY cadence, not daily like the EMA reports this
// pack's sibling packs cache — six hours would just mean six hours of
// needless re-downloads of an unchanged file. Twelve hours splits the
// difference between "fresh enough same-day" and "don't hammer a monthly
// file every six hours for nothing".
const DATASET_TTL_MS = 12 * 60 * 60 * 1000;
const HEADER_ROW = 7;

const FIELDS: Record<string, string> = {
  A: 'authorisation_number',
  B: 'dosage_number',
  C: 'name',
  D: 'holder',
  E: 'category',
  F: 'dispensing_category_dosage',
  G: 'dispensing_category_medicine',
  H: 'first_authorisation_date',
  I: 'dosage_authorisation_date',
  J: 'validity',
};
const DATE_FIELDS = new Set(['first_authorisation_date', 'dosage_authorisation_date']);

export type SwissmedicProduct = Record<string, string>;

interface Dataset {
  products: SwissmedicProduct[];
  fetchedAt: number;
  lastModified: string | null;
}

let CACHE: Dataset | null = null;
let INFLIGHT: Promise<Dataset> | null = null;

/** Excel serial date (days since 1899-12-30) -> ISO YYYY-MM-DD. */
function excelSerialToIso(serial: string): string {
  const n = Number(serial);
  if (!Number.isFinite(n) || n <= 0) return serial;
  const ms = Date.UTC(1899, 11, 30) + n * 86_400_000;
  const d = new Date(ms);
  if (Number.isNaN(d.getTime())) return serial;
  return d.toISOString().slice(0, 10);
}

async function load(): Promise<Dataset> {
  let res: Response;
  try {
    res = await pwFetch(XLSX_URL, {
      headers: { 'User-Agent': UA, Accept: '*/*' },
      cf: {
        cacheTtlByStatus: { '200-299': 43200, '400-499': 60, '500-599': 10 },
        cacheEverything: true,
      },
    } as RequestInit);
  } catch (e) {
    // This pack emits its own `user_error:` token (rejectUnknownArgs), so a
    // caught message that already starts with one of the shared routing
    // tokens (fetchWithTimeout can throw `upstream_down:`/`upstream_throttled:`)
    // must keep that token at position 0 — a plain template wrap pushes it
    // off position 0 and the gateway's classifier then books this as a
    // generic defect instead of the real class. See shared/src/error-prefix.ts.
    const { token, body } = splitClassPrefix((e as Error).message);
    throw new Error(`${token}swissmedic_fetch_failed:${body}`);
  }
  if (!res.ok) throw new Error(`swissmedic_http_${res.status}`);

  const lastModified = res.headers.get('last-modified');
  const buffer = await res.arrayBuffer();
  const entries = await unzipText(buffer, ['xl/worksheets/sheet1.xml', 'xl/sharedStrings.xml']);
  if (!entries['xl/worksheets/sheet1.xml']) throw new Error('swissmedic_no_sheet1');
  const shared = parseSharedStrings(entries['xl/sharedStrings.xml'] ?? '');
  const { rows } = scanSheet(entries['xl/worksheets/sheet1.xml'], shared);

  const products: SwissmedicProduct[] = [];
  for (const [rowNum, row] of rows) {
    if (rowNum <= HEADER_ROW) continue;
    const rec: SwissmedicProduct = {};
    for (const [col, field] of Object.entries(FIELDS)) {
      const raw = row[col];
      if (!raw) continue;
      rec[field] = DATE_FIELDS.has(field) ? excelSerialToIso(raw) : raw;
    }
    if (rec.name) products.push(rec);
  }
  if (products.length < 5_000) {
    throw new Error(
      `swissmedic_suspiciously_small:${products.length} rows parsed (expected ~11,000). Refusing to serve a truncated dataset.`,
    );
  }
  return { products, fetchedAt: Date.now(), lastModified };
}

async function dataset(): Promise<Dataset> {
  if (CACHE && Date.now() - CACHE.fetchedAt < DATASET_TTL_MS) return CACHE;
  if (INFLIGHT) return INFLIGHT;
  INFLIGHT = load()
    .then((d) => {
      CACHE = d;
      INFLIGHT = null;
      return d;
    })
    .catch((e) => {
      INFLIGHT = null;
      if (CACHE) return CACHE; // serve the stale copy rather than fail outright
      throw e;
    });
  return INFLIGHT;
}

function sourceBlock(ds: Dataset) {
  return {
    source: SOURCE,
    source_url: XLSX_URL,
    data_as_of: ds.lastModified ?? new Date(ds.fetchedAt).toISOString(),
    row_count: ds.products.length,
  };
}

function rejectUnknownArgs(args: Record<string, unknown>, accepted: readonly string[], toolLabel: string): void {
  const acceptedSet = new Set(accepted);
  const unknown = Object.keys(args).filter((k) => !k.startsWith('_') && !acceptedSet.has(k));
  if (unknown.length) {
    throw new Error(
      `user_error: ${toolLabel} does not recognise argument(s) ${unknown.map((k) => `"${k}"`).join(', ')}. ` +
        `They would otherwise be silently discarded rather than applied. Accepted arguments: ${accepted.join(', ')}.`,
    );
  }
}

